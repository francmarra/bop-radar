"""Map our car ids to GT7 car ids (gt7info cars.csv) -> data/car_images.toml."""

import csv
import io
import re
import tomllib
import unicodedata
from pathlib import Path

CSV_URL = "https://raw.githubusercontent.com/ddm999/gt7info/web-new/_data/db/cars.csv"
MANUAL = "# manual"
HEADER = "# car id -> GT7 id. Generated by `gt7bop images`; the hand-kept section starts at the marker line below.\n"


def normalise(name: str) -> str:
    """Lowercase, accents and punctuation stripped."""
    s = unicodedata.normalize("NFKD", name)
    return re.sub(r"[^a-z0-9]", "", "".join(c for c in s if not unicodedata.combining(c)).lower())


def match_ids(cars: list[dict], gt7_csv: str) -> tuple[dict[str, int], list[str], list[str]]:
    """(mapped, unmapped car ids, ambiguous car ids) by exact normalised name."""
    by_name: dict[str, set[int]] = {}
    for row in csv.DictReader(io.StringIO(gt7_csv)):
        by_name.setdefault(normalise(row["ShortName"]), set()).add(int(row["ID"]))
    mapped, unmapped, ambiguous = {}, [], []
    for car in cars:
        ids = by_name.get(normalise(car["name"]), set())
        if len(ids) == 1:
            mapped[car["id"]] = next(iter(ids))
        else:
            (ambiguous if ids else unmapped).append(car["id"])
    return mapped, unmapped, ambiguous


def read_mapping(path: Path) -> dict[str, int]:
    return tomllib.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def update_mapping(path: Path, cars: list[dict], gt7_csv: str) -> tuple[list[str], list[str]]:
    """Rewrite the generated part of the file; returns (still-unmapped, ambiguous)."""
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    m = re.search(rf"^{MANUAL}$", text, re.MULTILINE)
    manual = text[m.start():] if m else MANUAL + "\n"
    manual_ids = set(tomllib.loads(manual))
    mapped, unmapped, ambiguous = match_ids(cars, gt7_csv)
    lines = "".join(f'"{i}" = {n}\n' for i, n in sorted(mapped.items()) if i not in manual_ids)
    path.write_text(HEADER + lines + manual, encoding="utf-8")
    return [i for i in unmapped if i not in manual_ids], [i for i in ambiguous if i not in manual_ids]
