"""Map our car ids to GT7 car ids (gt7info cars.csv) -> data/car_images.toml."""

import csv
import io
import re
import time
import tomllib
import unicodedata
import urllib.request
from collections.abc import Callable
from pathlib import Path

CSV_URL = "https://raw.githubusercontent.com/ddm999/gt7info/web-new/_data/db/cars.csv"
THUMB_URL = "https://www.gran-turismo.com/common/dist/gt7/carlist/car_thumbnails/car{}.png"
USER_AGENT = "gt7-bop-radar (+https://github.com/francmarra/bop-radar)"
MAX_FAILS = 5
MANUAL = "# manual"
HEADER = "# car id -> GT7 id. Generated by `gt7bop images`; the hand-kept section starts at the marker line below.\n"


def normalise(name: str) -> str:
    """Lowercase, accents and punctuation stripped."""
    s = unicodedata.normalize("NFKD", name)
    return re.sub(r"[^a-z0-9]", "", "".join(c for c in s if not unicodedata.combining(c)).lower())


def match_ids(cars: list[dict], gt7_csv: str) -> tuple[dict[str, int], list[str], list[str]]:
    """(mapped, unmapped car ids, ambiguous car ids) by exact normalised name."""
    by_name: dict[str, set[int]] = {}
    for row in csv.DictReader(io.StringIO(gt7_csv)):
        by_name.setdefault(normalise(row["ShortName"]), set()).add(int(row["ID"]))
    mapped, unmapped, ambiguous = {}, [], []
    for car in cars:
        ids = by_name.get(normalise(car["name"]), set())
        if len(ids) == 1:
            mapped[car["id"]] = next(iter(ids))
        else:
            (ambiguous if ids else unmapped).append(car["id"])
    return mapped, unmapped, ambiguous


def read_mapping(path: Path) -> dict[str, int]:
    return tomllib.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def update_mapping(path: Path, cars: list[dict], gt7_csv: str) -> tuple[list[str], list[str]]:
    """Rewrite the generated part of the file; returns (still-unmapped, ambiguous)."""
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    m = re.search(rf"^{MANUAL}$", text, re.MULTILINE)
    manual = text[m.start():] if m else MANUAL + "\n"
    manual_ids = set(tomllib.loads(manual))
    mapped, unmapped, ambiguous = match_ids(cars, gt7_csv)
    lines = "".join(f'"{i}" = {n}\n' for i, n in sorted(mapped.items()) if i not in manual_ids)
    path.write_text(HEADER + lines + manual, encoding="utf-8")
    return [i for i in unmapped if i not in manual_ids], [i for i in ambiguous if i not in manual_ids]


def _get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=15) as resp:
        return resp.read()


def build_images(mapping: dict[str, int], out: Path, cache: Path, fetch: Callable[[str], bytes] = _get,
                 log=print, pause: float = 0.5) -> dict[str, list[int]]:
    """Download (once, into cache) and convert official car pictures; {car id: [w, h]} of the large file.
    Any problem with one picture skips that car (the site falls back to the silhouette)."""
    try:
        from PIL import Image  # optional dependency: `uv run --extra render`
    except ImportError:
        log("render: Pillow not installed, car pictures skipped")
        return {}

    out.mkdir(parents=True, exist_ok=True)
    cache.mkdir(parents=True, exist_ok=True)
    sizes: dict[str, list[int]] = {}
    fails, stopped = 0, False  # circuit breaker: consecutive network failures
    for car, gt7_id in sorted(mapping.items()):
        src = cache / f"{gt7_id}.png"
        try:
            if not src.exists():
                if stopped:
                    continue
                if pause:
                    time.sleep(pause)
                try:
                    data = fetch(THUMB_URL.format(gt7_id))
                except Exception:
                    fails += 1
                    if fails >= MAX_FAILS:
                        stopped = True
                        log(f"images: stopped downloading after {MAX_FAILS} consecutive failures")
                    raise
                fails = 0
                src.write_bytes(data)
            with Image.open(src) as im:
                im.load()
                large, small = im.copy(), im.copy()
            large.thumbnail((480, 10_000))  # width-bound; never upscales
            small.thumbnail((160, 10_000))
            large.save(out / f"{car}-l.webp", "WEBP", quality=82, method=6)
            small.save(out / f"{car}-s.webp", "WEBP", quality=82, method=6)
            sizes[car] = list(large.size)
        except Exception as exc:  # noqa: BLE001 - never fail the build over a picture
            src.unlink(missing_ok=True)  # a corrupt/partial download must not stay cached
            log(f"images: {car} (GT7 {gt7_id}) skipped: {exc!r}")
    return sizes
